import {chromium} from 'playwright';
import fs from 'node:fs';
import sharp from 'sharp';
const base=process.argv[2]||'http://localhost:3400';
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage(),failures=[],errors=[],samples=[];
page.setDefaultNavigationTimeout(120000);page.on('pageerror',e=>errors.push(e.message));
const check=(ok,message)=>{if(!ok)failures.push(message);};
fs.mkdirSync('screenshots/motion',{recursive:true});
await page.goto(base,{waitUntil:'networkidle'});
await page.locator('.display-ready').waitFor({timeout:60000});await page.waitForTimeout(1800);
await page.mouse.move(350,200);await page.waitForTimeout(1100);
const first=await page.locator('.opening-canvas').screenshot({path:'screenshots/motion/display-left.png'});
await page.mouse.move(1280,650);await page.waitForTimeout(1100);
const second=await page.locator('.opening-canvas').screenshot({path:'screenshots/motion/display-right.png'});
const a=await sharp(first).resize(180,125).removeAlpha().raw().toBuffer(),b=await sharp(second).resize(180,125).removeAlpha().raw().toBuffer();
const difference=a.reduce((n,value,i)=>n+Math.abs(value-b[i]),0)/a.length;
check(difference>1,'3D display visibly responds to pointer movement');samples.push({pointerPixelDifference:difference});
await page.screenshot({path:'screenshots/motion/desktop-opening.png'});
const jump=async y=>{await page.evaluate(y=>{window.__lenis?.scrollTo(y,{immediate:true});window.scrollTo(0,y);},y);await page.waitForTimeout(1000);};
const distance=await page.locator('.home-opening').evaluate(el=>el.offsetHeight-innerHeight);
for(const [name,p] of [['approach',.4],['screen',.72],['reveal',1]]){
 await jump(distance*p);
 await page.screenshot({path:'screenshots/motion/desktop-'+name+'.png'});
 const state=await page.evaluate(()=>({wipe:Number(getComputedStyle(document.querySelector('.opening-screen-wipe')).opacity),clip:getComputedStyle(document.querySelector('.opening-screen-wipe')).clipPath,title:Number(getComputedStyle(document.querySelector('.hero-content')).opacity)}));
 samples.push({name,...state});
 if(p===1){check(state.wipe>.98&&state.title<.05,'screen fills viewport and opening text clears');}
}
await page.locator('#selected-products').scrollIntoViewIfNeeded();await page.waitForTimeout(1000);
const card=page.locator('.project-image-link').first();await card.scrollIntoViewIfNeeded();await page.waitForTimeout(1000);
const rect=await card.boundingBox();await page.mouse.move(rect.x+rect.width*.3,rect.y+rect.height*.4);await page.waitForTimeout(500);
const before=await card.locator('.project-view').evaluate(el=>getComputedStyle(el).transform);
await page.mouse.move(rect.x+rect.width*.7,rect.y+rect.height*.6);await page.waitForTimeout(600);
const after=await card.locator('.project-view').evaluate(el=>getComputedStyle(el).transform);
check(before!==after,'product cursor follows the pointer');
check(await card.locator('.project-view').evaluate(el=>Number(getComputedStyle(el).opacity))>.9,'product cursor visible on hover');
await page.screenshot({path:'screenshots/motion/product-hover.png'});
await page.getByRole('button',{name:'Menu',exact:true}).click();await page.waitForTimeout(850);
check(await page.locator('#main').evaluate(el=>el.inert),'open menu makes underlying content inert');
await page.screenshot({path:'screenshots/motion/menu.png'});
await page.keyboard.press('Escape');await page.waitForTimeout(550);
check(await page.locator('#site-menu').count()===0,'Escape closes animated menu');
check(await page.getByRole('button',{name:'Menu',exact:true}).evaluate(el=>el===document.activeElement),'menu focus returns');
check(await page.locator('#main').evaluate(el=>!el.inert),'menu restores content interaction');
await page.locator('header').getByRole('link',{name:'About',exact:true}).click();await page.waitForURL('**/about');await page.waitForTimeout(1200);
check(await page.locator('h1').evaluate(el=>getComputedStyle(el).opacity)==='1','route heading settles visibly');
await page.goBack();await page.waitForTimeout(1400);
check(await page.locator('h1').count()===1,'back navigation restores homepage');
await page.emulateMedia({reducedMotion:'reduce'});await page.waitForTimeout(900);
check(await page.locator('canvas').count()===0,'runtime reduced motion removes canvas');
check(await page.evaluate(()=>!window.__lenis),'runtime reduced motion stops smooth scrolling');
check(await page.locator('.opening-stage').evaluate(el=>getComputedStyle(el).position)==='relative','runtime reduced motion removes pinning');
check(errors.length===0,'desktop runtime errors: '+errors.join(';'));
await context.close();
const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
const phone=await mobile.newPage();await phone.goto(base,{waitUntil:'networkidle'});await phone.waitForTimeout(1600);
check(await phone.locator('canvas').count()===0,'mobile uses lightweight fallback');
await phone.screenshot({path:'screenshots/motion/mobile-opening.png'});
await phone.getByRole('button',{name:'Menu',exact:true}).click();await phone.waitForTimeout(850);
await phone.screenshot({path:'screenshots/motion/mobile-menu.png'});
await phone.locator('#site-menu').getByRole('link',{name:'Products',exact:false}).first().click();await phone.waitForURL('**/products');await phone.waitForTimeout(1000);
check(await phone.locator('#main').evaluate(el=>!el.inert),'mobile navigation unlocks content');
check(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'mobile has no horizontal overflow');
const fallback=await browser.newContext({viewport:{width:1440,height:1000}});
await fallback.addInitScript(()=>{const original=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){if(type==='webgl2'||type==='webgl')return null;return original.call(this,type,...args);};});
const fp=await fallback.newPage();await fp.goto(base,{waitUntil:'networkidle'});await fp.waitForTimeout(1600);
check(await fp.locator('.opening-canvas').count()===0,'unsupported WebGL uses image fallback');
check(await fp.locator('.world-preview').count()===4,'all four product fallbacks are present');
for(const card of await fp.locator('.world-preview').all())check(await card.isVisible(),'fallback product image is visible');
await fallback.close();
await browser.close();
fs.writeFileSync('screenshots/motion/qa-results.json',JSON.stringify({checkedAt:new Date().toISOString(),samples,failures},null,2));
if(failures.length){console.error(failures.join('\n'));process.exitCode=1;}else console.log('Motion, pointer, keyboard, route and reduced-motion checks passed.');
